#!/usr/bin/env node
// Regenerate lib/opal/parser/convert.mjs from Prism's config.yml's `nodes:`
// section: one function per node type that converts the parser's node into
// the plain AST object, with the fields in config.yml order (the order of
// the generic conversion in lib/opal/parser/index.mjs, which it replaces for
// speed: no per-field plan or name tests, and one object shape per type).
// Locations are the parser's own { start, end } objects (each belongs to one
// node) instead of copies.
//
//   node tasks/parser/gen_convert.mjs --config=<path to prism/config.yml> [--check]
//
// Only needed when moving parser to a new Prism version; convert.mjs is
// committed. (Prism 1.9's config.yml comes with its gem:
// gems/prism-1.9.0/config.yml.)

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const target = join(root, "lib", "opal", "parser", "convert.mjs");
const configArg = process.argv.find((a) => a.startsWith("--config="));
if (!configArg) {
  console.error("usage: node tasks/parser/gen_convert.mjs --config=<path to prism/config.yml> [--check]");
  process.exit(2);
}
const config = readFileSync(configArg.slice("--config=".length), "utf8");

// [{ name, fields: [{ name, type }] }] of the `nodes:` section
const nodes = [];
const nodesSection = config.slice(config.search(/^nodes:$/m));
const names = [...nodesSection.matchAll(/^  - name: (\w+)$/gm)];
for (let i = 0; i < names.length; i++) {
  const start = names[i].index;
  const end = i + 1 < names.length ? names[i + 1].index : nodesSection.length;
  const fields = [...nodesSection.slice(start, end).matchAll(/^      - name: (\w+)\n        type: ([\w?[\]]+)$/gm)].map((m) => ({ name: m[1], type: m[2] }));
  nodes.push({ name: names[i][1], fields });
}

// Fields the generic conversion sets before the others (index.mjs's
// convertNode `switch`), in that order.
const SCOPE_TYPES = new Set(["ProgramNode", "ClassNode", "ModuleNode", "SingletonClassNode", "BlockNode", "LambdaNode"]);
function specials(type) {
  if (type === "SourceFileNode") return [["filepath", 'typeof n.filepath === "string" ? n.filepath : String(n.filepath ?? "")']];
  if (SCOPE_TYPES.has(type)) return [["locals", "h.ids(n.locals)"]];
  if (type === "IntegerNode") return [["value", "h.int(n.value)"]];
  if (type === "FloatNode") return [["value", "n.value ?? null"]];
  if (type === "RationalNode") return [["numerator", "h.int(n.numerator)"], ["denominator", "h.int(n.denominator)"]];
  return [];
}

// The conversion of a field, as the generic conversion has it (by the
// field's name first, then by its type).
function fieldCode(field) {
  const { name, type } = field;
  const value = `n.${name}`;
  if (name.endsWith("_loc")) return `h.loc(${value})`;
  if (name === "unescaped") return `${value} ?? null`;
  if (name === "name" || name === "binary_operator" || name === "read_name" || name === "write_name") return `h.constant(${value}, "${name}")`;
  if (name === "constant_ids") return `h.ids(${value})`;
  if (type === "node" || type === "node?") return `h.node(${value})`;
  if (type === "node[]" && name !== "locals") return `h.nodes(${value})`;
  return `h.value(${value}, "${name}")`;
}

const out = [
  "// Generated by tasks/parser/gen_convert.mjs from config.yml's `nodes:` section:",
  "// the conversion of each node type into the plain AST object, with the",
  "// fields in config.yml order (see convertNode in index.mjs, which gives the",
  "// helpers `h`).",
  "export function nodeConverters(h) {",
  "  return {",
];

for (const node of nodes) {
  const pre = specials(node.name);
  const preNames = new Set(pre.map(([key]) => key));
  const keys = [...pre, ...node.fields.filter((f) => !preNames.has(f.name)).map((f) => [f.name, fieldCode(f)])];
  // `locals` of a scope type is left out when the node has none
  const optionalLocals = SCOPE_TYPES.has(node.name);
  const literal = (withFlags, withLocals) => {
    const parts = [`type: "${node.name}"`, "location: h.loc(n.location)", "node_id: n.node_id ?? null"];
    if (withFlags) parts.push("flags");
    for (const [key, code] of keys) {
      if (key === "locals" && optionalLocals && !withLocals) continue;
      parts.push(`${key}: ${code}`);
    }
    return `{ ${parts.join(", ")} }`;
  };
  const result = (withLocals) => `flags.length > 0 ? ${literal(true, withLocals)} : ${literal(false, withLocals)}`;
  out.push(`    ${node.name}(n) {`);
  out.push(`      const flags = h.flags("${node.name}", n.flags);`);
  if (optionalLocals) out.push(`      if (n.locals === undefined) return ${result(false)};`);
  out.push(`      return ${result(true)};`);
  out.push("    },");
}
out.push("  };", "}", "");

const text = out.join("\n");
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== text) {
    console.error(`${target} is out of date; run node tasks/parser/gen_convert.mjs --config=...`);
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  console.log(`wrote ${target} (${nodes.length} node types)`);
}
