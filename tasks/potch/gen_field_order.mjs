#!/usr/bin/env node
// Regenerate lib/opal/potch/field_order.mjs from Prism's config.yml's `nodes:` section.
//
// The order the `fields:` entries appear in is the order C's generated
// serializer writes them in, which is the order this build's wire output has to
// emit. The conversion plan cache in lib/opal/potch/index.mjs is built from
// this table.
//
//   node tasks/potch/gen_field_order.mjs --config=<path to prism/config.yml> [--check]
//
// Only needed when moving potch to a new Prism version; field_order.mjs is
// committed.

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..");
const target = join(root, "lib", "opal", "potch", "field_order.mjs");
const configArg = process.argv.find((a) => a.startsWith("--config="));
if (!configArg) {
    console.error("usage: node tasks/potch/gen_field_order.mjs --config=<path to prism/config.yml> [--check]");
    process.exit(2);
}
const config = readFileSync(configArg.slice("--config=".length), "utf8");

const entries = [];
const names = [...config.matchAll(/^  - name: (\w+)$/gm)];

for (let i = 0; i < names.length; i++) {
    const start = names[i].index;
    const end = i + 1 < names.length ? names[i + 1].index : config.length;
    const fields = [...config.slice(start, end).matchAll(/^      - name: (\w+)$/gm)].map((m) => m[1]);
    if (fields.length > 0) entries.push([names[i][1], fields.join(" ")]);
}

const out = [
    "// Generated by tasks/potch/gen_field_order.mjs from config.yml's `nodes:` section:",
    "// the field order C's serializer is generated from, per node type, as a",
    "// space-separated list (split once per type when its plan is first built).",
    "export const NODE_FIELD_ORDER = {",
    ...entries.map(([name, fields]) => `    ${name}: "${fields}",`),
    "};",
    "",
].join("\n");

if (process.argv.includes("--check")) {
    const current = readFileSync(target, "utf8");
    if (current !== out) {
        console.error("lib/opal/potch/field_order.mjs is out of date with config.yml; run: node tasks/potch/gen_field_order.mjs --config=...");
        process.exit(1);
    }
    console.log(`lib/opal/potch/field_order.mjs matches config.yml (${entries.length} node types)`);
} else {
    writeFileSync(target, out);
    console.log(`wrote lib/opal/potch/field_order.mjs (${entries.length} node types)`);
}
