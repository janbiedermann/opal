// Ported from src/token_type.c.

import * as ast from "./ast.mjs";

// token number -> the PM_TOKEN_* identifier with its prefix stripped. C's
// pm_token_type_name was a switch that returned exactly this name, so a
// reverse map built from the ast exports reproduces it.
const PM_TOKEN_TYPE_NAMES = {};
for (const [key, value] of Object.entries(ast)) {
    if (key.startsWith("PM_TOKEN_") && typeof value === "number") {
        PM_TOKEN_TYPE_NAMES[value] = key.slice("PM_TOKEN_".length);
    }
}

export function pm_token_type_name(token_type) {
    return PM_TOKEN_TYPE_NAMES[token_type] ?? "";
}

