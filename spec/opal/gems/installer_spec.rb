require 'spec_helper'
require 'rubygems'
require 'fileutils'
require 'rubygems/installer'

describe 'Gem::Installer' do
  before :each do
    @dir = tmp('gem_installer')
    @src = File.join @dir, 'src'
    FileUtils.mkdir_p File.join(@src, 'lib')
    FileUtils.mkdir_p File.join(@src, 'bin')
    File.write File.join(@src, 'lib/tiny.rb'), "module Tiny\n  VERSION = '0.1.0'\nend\n"
    File.write File.join(@src, 'bin/tiny'), "#!/usr/bin/env ruby\nrequire 'tiny'\nputs Tiny::VERSION\n"
  end

  after :each do
    rm_r @dir
  end

  def tiny_spec
    Gem::Specification.new do |spec|
      spec.name          = 'tiny'
      spec.version       = '0.1.0'
      spec.summary       = 'A tiny gem.'
      spec.description   = 'A tiny gem for the specs.'
      spec.authors       = ['Opal']
      spec.email         = 'opal@example.com'
      spec.files         = ['lib/tiny.rb', 'bin/tiny']
      spec.executables   = ['tiny']
      spec.require_paths = ['lib']
      spec.homepage      = 'https://example.com/tiny'
      spec.license       = 'MIT'
    end
  end

  # The gem is built in @src, which holds the files its spec names; the path
  # of the .gem is answered. +skip_validation+ lets a spec that would not
  # validate - an extension, a dependency the checks below reject - be built
  # anyway, so the installer itself gets to say no.
  def build_gem(spec = tiny_spec, skip_validation = false)
    File.join @src, Dir.chdir(@src) { Gem::Package.build spec, skip_validation }
  end

  def install(path = build_gem, options = {})
    Gem::Installer.at(path, {install_dir: @dir, wrappers: true}.merge(options)).install
  end

  def checks_message(path)
    installer = Gem::Installer.at(path, install_dir: @dir)

    begin
      installer.pre_install_checks
    rescue Gem::InstallError => e
      return e.message
    end

    fail 'Gem::InstallError expected, none raised'
  end

  it 'unpacks the gem, writes the gemspec and caches the gem' do
    install

    File.directory?(File.join(@dir, 'gems/tiny-0.1.0/lib')).should == true
    File.read(File.join(@dir, 'gems/tiny-0.1.0/lib/tiny.rb')).should include "VERSION = '0.1.0'"
    File.exist?(File.join(@dir, 'cache/tiny-0.1.0.gem')).should == true

    gemspec = File.join(@dir, 'specifications/tiny-0.1.0.gemspec')
    File.exist?(gemspec).should == true
    Gem::Specification.load(gemspec).full_name.should == 'tiny-0.1.0'
  end

  it 'records the RubyGems that installed it' do
    install

    Gem::Specification.load(File.join(@dir, 'specifications/tiny-0.1.0.gemspec'))
      .installed_by_version.to_s.should == Gem::VERSION
  end

  it 'makes the installed gem findable by scanning the directory' do
    install

    record = Gem::SpecificationRecord.from_path @dir
    record.stubs.map(&:full_name).should == ['tiny-0.1.0']
    record.find_all_by_name('tiny').first.version.to_s.should == '0.1.0'
  end

  it 'writes a wrapper that activates the gem and loads its executable' do
    install

    wrapper_path = File.join @dir, 'bin/tiny'
    wrapper = File.read wrapper_path
    wrapper.should include 'This file was generated by RubyGems'
    wrapper.should include "Gem.activate_and_load_bin_path('tiny', 'tiny'"
    wrapper.should =~ %r{\A#!/usr/bin/env ruby}

    (File.stat(wrapper_path).mode & 0o111).should > 0
  end

  it 'links to the executable instead, without wrappers' do
    install build_gem, wrappers: false

    link = File.join @dir, 'bin/tiny'
    File.symlink?(link).should == true
    File.readlink(link).should == File.join(@dir, 'gems/tiny-0.1.0/bin/tiny')
  end

  it 'leaves a gem that declares native extensions uninstalled' do
    FileUtils.mkdir_p File.join(@src, 'ext/tiny')
    File.write File.join(@src, 'ext/tiny/extconf.rb'), ''

    spec = tiny_spec
    spec.files = spec.files + ['ext/tiny/extconf.rb']
    spec.extensions = ['ext/tiny/extconf.rb']

    checks_message(build_gem(spec, true)).should include 'native extensions'
    File.directory?(File.join(@dir, 'gems/tiny-0.1.0')).should == false
  end

  it 'refuses a gem whose dependencies are not installed' do
    spec = tiny_spec
    spec.add_dependency 'rake', '>= 13'

    checks_message(build_gem(spec, true)).should include 'tiny requires'
  end

  it 'installs over a missing dependency when forced' do
    spec = tiny_spec
    spec.add_dependency 'rake', '>= 13'

    install(build_gem(spec, true), force: true).full_name.should == 'tiny-0.1.0'
  end

  it 'reads the spec of the .gem file it is given' do
    path = build_gem

    Gem::Package.new(path).spec.full_name.should == 'tiny-0.1.0'
    Gem::Source::SpecificFile.new(path).spec.full_name.should == 'tiny-0.1.0'
  end
end
